function drawSuccessAndRating(doc, fonts, reportData, watermarkText) {
  drawSectionTitle(doc, fonts, 'Success Rate + Average Rating', 'Operational conversion and customer sentiment at a glance', watermarkText);
  ensureSpace(doc, fonts, watermarkText, 130);

  const y = doc.y;
  const width = (doc.page.width - 96) / 2;
  const successRate = safeNumber(reportData.success_rate);
  const averageRating = safeNumber(reportData.average_rating);

  drawPanel(doc, 40, y, width, 108, COLORS.panel, COLORS.line, 20);
  setFont(doc, fonts, 'regular', 10, COLORS.muted);
  doc.text('Answer Success Rate', 58, y + 16);
  setFont(doc, fonts, 'heading', 25, COLORS.ink);
  doc.text(formatPercent(successRate), 58, y + 36);
  doc.save();
  doc.roundedRect(58, y + 74, width - 36, 12, 6).fill('#edf3fb');
  doc.roundedRect(58, y + 74, Math.max(8, (width - 36) * Math.min(successRate, 100) / 100), 12, 6).fill(COLORS.blue);
  doc.restore();

  drawPanel(doc, 56 + width, y, width, 108, COLORS.panel, COLORS.line, 20);
  setFont(doc, fonts, 'regular', 10, COLORS.muted);
  doc.text('Average Rating', 74 + width, y + 16);
  setFont(doc, fonts, 'heading', 25, COLORS.ink);
  doc.text(`${averageRating.toFixed(1)}/5`, 74 + width, y + 36);
  setFont(doc, fonts, 'regular', 10, COLORS.muted);
  doc.text(`Based on ${safeNumber(reportData.feedback_count)} feedback entries`, 74 + width, y + 72);

  doc.y = y + 126;
}

function drawBreakdownBar(doc, fonts, x, y, label, count, pct, color) {
  setFont(doc, fonts, 'regular', 10, COLORS.muted);
  doc.text(label, x, y);
  setFont(doc, fonts, 'heading', 10, COLORS.ink);
  doc.text(`${count} (${pct}%)`, x + 248, y, { width: 120, align: 'right' });

  doc.save();
  doc.roundedRect(x, y + 18, 368, 12, 6).fill('#edf3fb');
  const barWidth = pct > 0 ? (368 * pct) / 100 : 0;
  if (barWidth > 0) {
    doc.roundedRect(x, y + 18, barWidth, 12, 6).fill(color);
  }
  doc.restore();
}

function drawFeedbackBreakdown(doc, fonts, reportData, watermarkText) {
  const good = safeNumber(reportData.good_count);
  const average = safeNumber(reportData.average_count);
  const bad = safeNumber(reportData.bad_count);
  const total = good + average + bad;
  const goodPct = total > 0 ? Number(((good / total) * 100).toFixed(1)) : 0;
  const averagePct = total > 0 ? Number(((average / total) * 100).toFixed(1)) : 0;
  const badPct = total > 0 ? Number(((bad / total) * 100).toFixed(1)) : 0;

  drawSectionTitle(doc, fonts, 'Feedback Breakdown', 'Distribution of good, average, and bad customer responses', watermarkText);
  ensureSpace(doc, fonts, watermarkText, 168);

  const y = doc.y;
  drawPanel(doc, 40, y, doc.page.width - 80, 138, COLORS.soft, COLORS.line, 20);
  drawBreakdownBar(doc, fonts, 60, y + 22, 'Good', good, goodPct, COLORS.green);
  drawBreakdownBar(doc, fonts, 60, y + 60, 'Average', average, averagePct, COLORS.orange);
  drawBreakdownBar(doc, fonts, 60, y + 98, 'Bad', bad, badPct, COLORS.red);
  doc.y = y + 156;
}

function drawBulletList(doc, fonts, items, watermarkText, emptyText) {
  const rows = Array.isArray(items) ? items.filter(Boolean) : [];
  if (!rows.length) {
    ensureSpace(doc, fonts, watermarkText, 72);
    const y = doc.y;
    drawPanel(doc, 40, y, doc.page.width - 80, 56, COLORS.soft, COLORS.line, 16);
    setFont(doc, fonts, 'regular', 10, COLORS.muted);
    doc.text(emptyText, 60, y + 20);
    doc.y = y + 72;
    return;
  }

  rows.forEach((item) => {
    const height = Math.max(44, doc.heightOfString(item, { width: doc.page.width - 130 }) + 20);
    ensureSpace(doc, fonts, watermarkText, height + 10);
    const y = doc.y;
    drawPanel(doc, 40, y, doc.page.width - 80, height, COLORS.panel, COLORS.line, 16);
    doc.save();
    doc.circle(62, y + 20, 4).fill(COLORS.blue);
    doc.restore();
    setFont(doc, fonts, 'regular', 10, COLORS.ink);
    doc.text(item, 78, y + 12, { width: doc.page.width - 140 });
    doc.y = y + height + 10;
  });
}

function drawKeyInsights(doc, fonts, reportData, watermarkText) {
  drawSectionTitle(doc, fonts, 'Key Insights', 'High-signal observations extracted from analyzed calls', watermarkText);
  const insights = (reportData.analyzed_calls || [])
    .map((call) => call.analysis_summary || call.report_excerpt)
    .filter(Boolean)
    .slice(0, 6);

  drawBulletList(doc, fonts, insights, watermarkText, 'No AI insights available yet for this report window.');
}

function drawAlerts(doc, fonts, reportData, watermarkText) {
  drawSectionTitle(doc, fonts, 'Alerts / Pending Items', 'Items that still need operator follow-up or pipeline completion', watermarkText);
  const items = (reportData.pending_items || []).map((item) => {
    const parts = [
      `${item.customer_name || 'Customer'} at ${formatDate(item.called_at)}`,
      `Outcome: ${item.outcome || 'n/a'}`,
      `Recording: ${item.recording_status || 'pending'}`,
      `Transcript: ${item.transcript_status || 'pending'}`,
      `Analysis: ${item.analysis_status || 'pending'}`
    ];

    return parts.join(' | ');
  });

  drawBulletList(doc, fonts, items, watermarkText, 'No pending alerts. Recording, transcript, and analysis pipeline look healthy.');
}

function drawCallDetailCard(doc, fonts, call, watermarkText) {
  const detailLines = [
    `Customer: ${call.customer_name || 'Customer'} | Called at: ${formatDate(call.called_at)}`,
    `Outcome: ${call.outcome || 'n/a'} | Rating: ${call.extracted_rating || 'N/A'}/5`,
    `Recording: ${call.recording_status || 'pending'} | Transcript: ${call.transcript_status || 'pending'} | Analysis: ${call.analysis_status || 'pending'}`
  ];

  const transcriptPreview = call.transcript_text
    ? call.transcript_text.replace(/\s+/g, ' ').slice(0, 180)
    : 'Transcript pending or unavailable.';
  const baseHeight = 118;
  const previewHeight = doc.heightOfString(transcriptPreview, { width: doc.page.width - 140 });
  const cardHeight = Math.max(baseHeight, 92 + previewHeight);

  ensureSpace(doc, fonts, watermarkText, cardHeight + 12);
  const y = doc.y;
  drawPanel(doc, 40, y, doc.page.width - 80, cardHeight, COLORS.panel, COLORS.line, 18);

  let lineY = y + 16;
  detailLines.forEach((line) => {
    setFont(doc, fonts, lineY === y + 16 ? 'heading' : 'regular', lineY === y + 16 ? 11 : 9, lineY === y + 16 ? COLORS.ink : COLORS.muted);
    doc.text(line, 58, lineY, { width: doc.page.width - 116 });
    lineY += lineY === y + 16 ? 22 : 18;
  });

  // setFont(doc, fonts, 'regular', 10, COLORS.ink);
  // doc.text(`Transcript preview: ${transcriptPreview}`, 58, y + 74, {
  //   width: doc.page.width - 116
  // });

  const linkY = y + cardHeight - 24;
  if (call.recording_link) {
    setFont(doc, fonts, 'regular', 9, COLORS.blue);
    doc.text('Recording link', 58, linkY, { link: call.recording_link, underline: true });
  }
  if (call.transcript_link) {
    setFont(doc, fonts, 'regular', 9, COLORS.blue);
    doc.text('Transcript link', 148, linkY, { link: call.transcript_link, underline: true });
  }

  doc.y = y + cardHeight + 10;
}

function drawCallDetails(doc, fonts, reportData, watermarkText) {
  drawSectionTitle(doc, fonts, 'Call Details', 'Operational call records with quick access to recordings and transcripts', watermarkText);
  const calls = Array.isArray(reportData.analyzed_calls) ? reportData.analyzed_calls.slice(0, 6) : [];

  if (!calls.length) {
    drawBulletList(doc, fonts, [], watermarkText, 'No call details available for this report window.');
    return;
  }

  calls.forEach((call) => drawCallDetailCard(doc, fonts, call, watermarkText));
}

