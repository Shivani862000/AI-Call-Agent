const PDFDocument = require('pdfkit');
const fs = require('fs');

const COLORS = {
  ink: '#15233b',
  muted: '#6e7e99',
  line: '#d9e4f2',
  soft: '#f6f9ff',
  blue: '#2d6df6',
  blueSoft: '#e9f1ff',
  green: '#2ea043',
  greenSoft: '#eaf7ee',
  orange: '#ff9b17',
  orangeSoft: '#fff2df',
  red: '#ea5455',
  redSoft: '#ffe8e8',
  panel: '#ffffff',
  dark: '#14213d'
};

function resolveFontPath() {
  const candidates = [
    '/System/Library/Fonts/Supplemental/Arial Unicode.ttf',
    '/Library/Fonts/Arial Unicode.ttf'
  ];

  return candidates.find((fontPath) => fs.existsSync(fontPath)) || null;
}

function registerFonts(doc) {
  const unicodeFontPath = resolveFontPath();
  if (unicodeFontPath) {
    doc.registerFont('ReportUnicode', unicodeFontPath);
    return { regular: 'ReportUnicode', heading: 'ReportUnicode' };
  }

  return { regular: 'Helvetica', heading: 'Helvetica-Bold' };
}

function setFont(doc, fonts, type = 'regular', size = 10, color = COLORS.ink) {
  doc.font(type === 'heading' ? fonts.heading : fonts.regular)
    .fontSize(size)
    .fillColor(color);
}

function drawPanel(doc, x, y, width, height, fill = COLORS.panel, stroke = COLORS.line, radius = 18) {
  doc.save();
  doc.roundedRect(x, y, width, height, radius).fillAndStroke(fill, stroke);
  doc.restore();
}

function drawWatermark(doc, fonts, text) {
  if (!text) return;

  const centerX = doc.page.width / 2;
  const centerY = doc.page.height / 2;

  doc.save();
  doc.fillOpacity(0.06);
  doc.rotate(-32, { origin: [centerX, centerY] });
  doc.font(fonts.heading).fontSize(54).fillColor(COLORS.blue);
  doc.text(text, centerX - 240, centerY - 28, {
    width: 480,
    align: 'center',
    lineBreak: false
  });
  doc.restore();
}

function drawFooter(doc, fonts) {
  const footerY = doc.page.height - doc.page.margins.bottom - 12;
  setFont(doc, fonts, 'regular', 8, COLORS.muted);
  doc.text('Generated by Feedback Automation System', 40, footerY, {
    width: doc.page.width - 80,
    align: 'center',
    lineBreak: false
  });
}

function decoratePage(doc, fonts, watermarkText) {
  drawWatermark(doc, fonts, watermarkText);
  drawFooter(doc, fonts);
}

function addPage(doc, fonts, watermarkText) {
  doc.addPage();
  decoratePage(doc, fonts, watermarkText);
  doc.y = 46;
}

function getBottomLimit(doc) {
  return doc.page.height - doc.page.margins.bottom - 28;
}

function ensureSpace(doc, fonts, watermarkText, requiredHeight) {
  if (doc.y + requiredHeight <= getBottomLimit(doc)) {
    return;
  }

  addPage(doc, fonts, watermarkText);
}

function safeNumber(value, fallback = 0) {
  return Number.isFinite(Number(value)) ? Number(value) : fallback;
}

function formatPercent(value) {
  return `${safeNumber(value).toFixed(1)}%`;
}

function formatDate(value) {
  if (!value) return 'N/A';
  return new Date(value).toLocaleString();
}

function drawHeader(doc, fonts, reportData, watermarkText) {
  drawPanel(doc, 40, 34, doc.page.width - 80, 124, COLORS.dark, COLORS.dark, 28);

  setFont(doc, fonts, 'regular', 12, '#c8d8ff');
  doc.text('Daily Feedback Report', 66, 56);

  setFont(doc, fonts, 'heading', 27, '#ffffff');
  doc.text(watermarkText, 66, 78, { width: doc.page.width - 132 });

  setFont(doc, fonts, 'regular', 11, '#dce6ff');
  doc.text(`Report date: ${new Date(reportData.date || Date.now()).toLocaleDateString()}`, 66, 118);
  doc.text(`Prepared at: ${new Date().toLocaleString()}`, 66, 136);

  if (reportData.dashboard_link) {
    setFont(doc, fonts, 'regular', 10, '#c8d8ff');
    doc.text('Open dashboard', doc.page.width - 165, 118, {
      link: reportData.dashboard_link,
      underline: true
    });
  }

  doc.y = 178;
}

function drawSectionTitle(doc, fonts, title, subtitle, watermarkText) {
  ensureSpace(doc, fonts, watermarkText, 46);
  setFont(doc, fonts, 'heading', 16, COLORS.ink);
  doc.text(title, 40, doc.y);

  if (subtitle) {
    setFont(doc, fonts, 'regular', 9, COLORS.muted);
    doc.text(subtitle, 40, doc.y + 4);
  }

  doc.moveDown(1.3);
}

