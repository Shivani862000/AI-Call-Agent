grant usage on schema public to ai_call_agent_runtime;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'clients',
    'app_users',
    'app_user_roles',
    'customers',
    'calls',
    'feedback',
    'call_supervisor_events',
    'application_state',
    'agents',
    'campaign_configurations',
    'support_tickets'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all privileges on table public.%I from public, anon, authenticated, service_role', table_name);
    execute format('grant select, insert, update, delete on table public.%I to ai_call_agent_runtime', table_name);
    execute format(
      'create policy %I on public.%I for all to ai_call_agent_runtime using (true) with check (true)',
      table_name || '_runtime_all',
      table_name
    );
  end loop;
end
$$;

revoke all privileges on all sequences in schema public from public, anon, authenticated, service_role;
grant usage, select on all sequences in schema public to ai_call_agent_runtime;

alter default privileges in schema public revoke all on tables from anon, authenticated, service_role;
alter default privileges in schema public revoke all on sequences from anon, authenticated, service_role;

commit;
