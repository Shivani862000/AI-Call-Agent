do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'ai_call_agent_runtime') then
    create role ai_call_agent_runtime
      nologin
      nosuperuser
      nocreatedb
      nocreaterole
      noreplication
      nobypassrls;
  end if;
